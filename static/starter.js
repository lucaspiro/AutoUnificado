/* Sketch de ejemplo precargado. Estilo Arduino IDE: anda igual aca y en la placa.
   Maneja los 3 modos (manual / ultrasonido / siguelinea) segun el request. */
window.STARTER_SKETCH = [
"#include <WiFiS3.h>",
"",
"// ---- Pines de motores (deben coincidir con la Configuracion) ----",
"const int IN1 = 5, IN2 = 6, IN3 = 10, IN4 = 11;",
"",
"// ---- Ultrasonido ----",
"const int TRIG_F = 9, ECHO_F = 8;",
"const int TRIG_I = 12, ECHO_I = 13;",
"const int TRIG_D = 7, ECHO_D = 4;",
"",
"// ---- Infrarrojo (siguelinea) ----",
"const int IR_IZQ = A0, IR_DER = A1;",
"",
"int velocidad = 150;",
"int umbral = 500;",
"String modo = \"manual\";",
"",
"long sensor_frontal = 200, sensor_izq = 200, sensor_der = 200;",
"int linea_izq = 0, linea_der = 0;",
"",
"WiFiServer server(80);",
"",
"long leerDistancia(int trig, int echo) {",
"  digitalWrite(trig, LOW); delayMicroseconds(2);",
"  digitalWrite(trig, HIGH); delayMicroseconds(10); digitalWrite(trig, LOW);",
"  long dur = pulseIn(echo, HIGH, 25000);",
"  if (dur == 0) return 200;",
"  return dur * 0.034 / 2;",
"}",
"",
"void motores(int izq, int der) {",
"  analogWrite(IN1, izq > 0 ? izq : 0);",
"  analogWrite(IN2, izq < 0 ? -izq : 0);",
"  analogWrite(IN3, der > 0 ? der : 0);",
"  analogWrite(IN4, der < 0 ? -der : 0);",
"}",
"void avanzar()    { motores(velocidad, velocidad); }",
"void retroceder() { motores(-velocidad, -velocidad); }",
"void girarIzq()   { motores(-velocidad, velocidad); }",
"void girarDer()   { motores(velocidad, -velocidad); }",
"void parar()      { motores(0, 0); }",
"",
"void manual(String r) {",
"  if (r.indexOf(\"/adelante\") >= 0) avanzar();",
"  else if (r.indexOf(\"/atras\") >= 0) retroceder();",
"  else if (r.indexOf(\"/izquierda\") >= 0) girarIzq();",
"  else if (r.indexOf(\"/derecha\") >= 0) girarDer();",
"  else if (r.indexOf(\"/stop\") >= 0) parar();",
"}",
"",
"void ultrasonido() {",
"  sensor_frontal = leerDistancia(TRIG_F, ECHO_F);",
"  sensor_izq = leerDistancia(TRIG_I, ECHO_I);",
"  sensor_der = leerDistancia(TRIG_D, ECHO_D);",
"  if (sensor_frontal > 20) avanzar();",
"  else if (sensor_izq > sensor_der) girarIzq();",
"  else girarDer();",
"}",
"",
"void siguelinea() {",
"  linea_izq = analogRead(IR_IZQ);",
"  linea_der = analogRead(IR_DER);",
"  if (linea_izq < umbral && linea_der < umbral) avanzar();",
"  else if (linea_izq > umbral) girarIzq();",
"  else if (linea_der > umbral) girarDer();",
"  else parar();",
"}",
"",
"void atender() {",
"  WiFiClient client = server.available();",
"  if (client) {",
"    String req = client.readStringUntil('\\n');",
"    Serial.print(\"Request: \"); Serial.println(req);",
"    if (req.indexOf(\"vel=\") >= 0) {",
"      int pos = req.indexOf(\"vel=\");",
"      velocidad = req.substring(pos + 4).toInt();",
"    }",
"    if (req.indexOf(\"/manual\") >= 0) modo = \"manual\";",
"    else if (req.indexOf(\"/automatico\") >= 0 || req.indexOf(\"/ultra\") >= 0) modo = \"ultra\";",
"    else if (req.indexOf(\"/siguelinea\") >= 0 || req.indexOf(\"/linea\") >= 0) modo = \"linea\";",
"    else if (modo == \"manual\") manual(req);",
"    client.stop();",
"  }",
"}",
"",
"void setup() {",
"  Serial.begin(9600);",
"  server.begin();",
"  Serial.println(\"Auto listo\");",
"}",
"",
"void loop() {",
"  atender();",
"  if (modo == \"ultra\") ultrasonido();",
"  else if (modo == \"linea\") siguelinea();",
"}"
].join("\n");
